#!/usr/bin/env python3
"""Print the power-of-five table that std/json.rig's float parser uses.

usage: bench/json/gen-json-tables.py [--check FILE.rs] > table.txt

POW5_HI[i] and POW5_LO[i] are the high and low 64 bits of 5^q for
q = i - 342, normalized so the top bit is set and truncated to 128 bits
(rounded up by one for negative q), as fast_float and Rust's dec2flt
tabulate it. The output replaces the GENERATED block of std/json.rig.
With --check, compare against a Rust table such as
sonic-rs's sonic-number/src/table.rs.
"""
import re, sys

def table():
    out = []
    for q in range(-342, 0):
        p5 = 5 ** -q
        z = 0
        while (1 << z) < p5:
            z += 1
        if q >= -27:
            c = 2 ** (z + 127) // p5 + 1
        else:
            c = 2 ** (2 * z + 128) // p5 + 1
            while c >= (1 << 128):
                c //= 2
        out.append(c)
    for q in range(0, 309):
        p5 = 5 ** q
        while p5 < (1 << 127):
            p5 *= 2
        while p5 >= (1 << 128):
            p5 //= 2
        out.append(p5)
    return out

def main():
    t = table()
    if len(sys.argv) == 3 and sys.argv[1] == "--check":
        pairs = re.findall(r"\(0x([0-9a-f]+),\s*0x([0-9a-f]+)\)", open(sys.argv[2]).read())
        want = [(int(a, 16) << 64) | int(b, 16) for a, b in pairs]
        bad = [i for i, (x, y) in enumerate(zip(t, want)) if x != y]
        print("%d entries, %d in the Rust table, %d differ" % (len(t), len(want), len(bad)))
        return 1 if bad or len(t) != len(want) else 0
    def emit(name, words):
        print("%s: [%d]U64 = [" % (name, len(words)))
        for i in range(0, len(words), 4):
            print("  " + ", ".join("0x%016x" % w for w in words[i:i + 4]) + ",")
        print("]")
    print("# BEGIN GENERATED by bench/json/gen-json-tables.py: 5^q for q in -342..308")
    emit("POW5_HI", [x >> 64 for x in t])
    print()
    emit("POW5_LO", [x & (2 ** 64 - 1) for x in t])
    print("# END GENERATED")
    return 0

sys.exit(main())
